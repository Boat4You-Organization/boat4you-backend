package hr.workspace.boat4you.domains.reservation.controllers

import hr.workspace.boat4you.domains.reservation.dto.CardCheckoutRequest
import hr.workspace.boat4you.domains.reservation.dto.CheckoutSessionDto
import hr.workspace.boat4you.domains.reservation.service.payment.CardPaymentRouter
import io.swagger.v3.oas.annotations.Operation
import io.swagger.v3.oas.annotations.Parameter
import io.swagger.v3.oas.annotations.tags.Tag
import jakarta.validation.Valid
import org.springframework.http.ResponseEntity
import org.springframework.security.access.prepost.PreAuthorize
import org.springframework.stereotype.Controller
import org.springframework.validation.annotation.Validated
import org.springframework.web.bind.annotation.PathVariable
import org.springframework.web.bind.annotation.PostMapping
import org.springframework.web.bind.annotation.RequestBody
import org.springframework.web.bind.annotation.RequestMapping
import org.springframework.web.bind.annotation.RequestParam

/**
 * Card checkout (Mollie) for logged-in bookers.
 * Errors: 400 invalid phase selection, 404 unknown reservation / status reference, 409 (8102 in progress,
 * 8103 already paid), 502 (8104) provider error, 503 (8101) Mollie not configured.
 */
@Tag(name = "Payments")
@Validated
@Controller
@RequestMapping("/secured/payments/card")
@PreAuthorize("isAuthenticated()")
class CardPaymentController(
    private val router: CardPaymentRouter,
) {
    @Operation(summary = "Create a card checkout (Mollie)")
    @PostMapping("/create-checkout-session/{reservationId}")
    fun createCheckoutSession(
        @PathVariable reservationId: Long,
        @Parameter(description = "Pay the full remaining amount instead of the first due installment. Used when creating a reservation")
        @RequestParam(value = "payFullAmount", required = false)
        payFullAmount: Boolean? = null,
        @Parameter(description = "Pay a specific installment (wins over payFullAmount)")
        @RequestParam(value = "paymentPhaseId", required = false)
        paymentPhaseId: Long? = null,
        @Parameter(description = "Generated by the web per /payment page mount; dedupes double clicks")
        @RequestParam(value = "idempotencyKey", required = false)
        idempotencyKey: String? = null,
        @Parameter(description = "Web locale (next-intl), used for the provider's return URL")
        @RequestParam(value = "locale", required = false)
        locale: String? = null,
        @Valid
        @RequestBody(required = false)
        body: CardCheckoutRequest? = null,
    ): ResponseEntity<CheckoutSessionDto> =
        ResponseEntity.ok(router.createCheckout(reservationId, payFullAmount, paymentPhaseId, idempotencyKey, locale, body?.klarna))

    @Operation(summary = "Check a card payment status by its checkout reference (404 when unknown)")
    @PostMapping("/checkPaymentStatus/{ref}")
    fun checkPaymentStatus(
        @PathVariable ref: String,
    ): ResponseEntity<CheckoutSessionDto> = ResponseEntity.ok(router.checkStatus(ref))
}
