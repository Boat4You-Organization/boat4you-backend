-- Equipment link fix, data (equipment audit 8.10.2026, FIX_CONTRACT 9). Brings every partner yacht_equipment row to
-- the link the new sync (EquipmentLinkResolver: explicit mapping, then the best-hit EquipmentMatcher on the R__1_05 v2
-- keys) gives it, so the public "linked rows only" rule hides nothing that is shown today and the first sync after the
-- deploy has nothing to change (0 differences on the 8.10. prod snapshot).
--   S0  catalogue rows the links point at, created when missing (cockpit-cushions, depth-sounder; values and keys are
--       owned by R__1_05, which runs after this file in the same Flyway run)
--   S1  merges: bow-thruster-deck -> bow-thruster, refrigerator -> fridge, sundeck-cushions -> sun-pads
--       (equipment.merged_into_id, then every row on an alias moves to the canonical code)
--   S2  A': 67 verified partner catalogue items still on their current wrong code (system, item, current code)
--   S3  MMK free text (external_id -1): every row is linked by ITS OWN exact name; a name missing here gets NULL (the
--       old sync collapsed all free-text items of a yacht into one row that borrowed another item's link)
--   S4  partner catalogue items by (system, item, exact name): newly linked (WiFi, plotters, ...), relinked, unlinked
-- Everything by label_code, never by numeric equipment id. Rows outside these keys (synced after the snapshot) stay as
-- they are and the next sync recomputes them. Idempotent: a second run changes nothing.
-- Flyway only, or psql --single-transaction -f: SET LOCAL and the ON COMMIT DROP temp tables need ONE transaction
-- (plain psql -f autocommits every statement, drops each temp table at once and fails at the next statement).
-- Runs while the sync node (cusma3) is stopped, so nothing else writes yacht_equipment; the API only reads (MVCC).
-- One transaction (~133k rows on the snapshot, seconds on PG18); a held row lock fails it atomically after 10 s.
-- Backup: every changed row once, before its first change, in _equipment_link_fix_backup_20261008.
-- Rollback (data): UPDATE yacht_equipment ye SET equipment_id = b.equipment_id_before
--                  FROM _equipment_link_fix_backup_20261008 b WHERE b.ye_id = ye.id;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '10min';

CREATE TABLE IF NOT EXISTS _equipment_link_fix_backup_20261008 (
    ye_id               bigint PRIMARY KEY,
    yacht_id            bigint      NOT NULL,
    external_system_id  integer,
    external_id         bigint,
    name                varchar,
    equipment_id_before bigint,
    section             text        NOT NULL,
    backed_up_at        timestamptz NOT NULL DEFAULT now()
);

-- Partner system of each yacht (external_mapping type 'Yacht': 1 = MMK, 2 = NauSys); a yacht mapped to both is left out.
DROP TABLE IF EXISTS _eqfix_yacht_system;
CREATE TEMP TABLE _eqfix_yacht_system ON COMMIT DROP AS
SELECT em.system_id AS yacht_id, min(em.external_system_id) AS external_system_id
FROM external_mapping em
WHERE em.type = 'Yacht'
GROUP BY em.system_id
HAVING count(DISTINCT em.external_system_id) = 1;
ALTER TABLE _eqfix_yacht_system ADD PRIMARY KEY (yacht_id);

